- 気温の線が一年中高く平ら→熱帯。一年中10℃台前半で平ら→低緯度の高山気候。
- 夏に雨が少なく冬に多い→地中海性気候。降水量の棒が一年中ほとんどない→乾燥帯。
- 年較差が大きい→内陸の大陸性気候。小さい→海洋性気候。

