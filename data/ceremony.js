{{steps:右手でひしゃくを持って水をくみ、左手を清める|左手に持ちかえ、右手を清める|右手に持ちかえ、左の手のひらに水を受けて口をすすぐ|もう一度左手を清め、ひしゃくを立てて柄を流す}}

